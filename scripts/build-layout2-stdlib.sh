#!/usr/bin/env bash
#
# Build the compiler *and* the target standard library with the GNUstep class
# layout (layout 2), in the existing build tree, and write a wrapper that uses
# that compiler with that stdlib.
#
#   swift-toolchain/scripts/build-layout2-stdlib.sh
#
# Why the stdlib as well: a generic class's metadata is built at runtime, by the
# runtime in the stdlib, so a layout-2 compiler needs a layout-2 runtime (the
# mismatched pair leaves `InstanceSize` unwritten and corrupts the heap for any
# field wider than a word).  Layout 2 is now the default and the installed
# toolchain is layout 2; this script remains the way to build a matched pair
# *inside the build tree* without touching the installation - handy for testing
# a compiler change before installing it.
#
# Nothing is installed.  Products, all inside the build tree:
#
#   bin/swift-frontend            layout-2 compiler
#   lib/swift/...                 layout-2 stdlib (and its .swiftmodules)
#   bin/swiftc-layout2-stdlib     wrapper: the above, with the host runtime
#
# The wrapper keeps the compiler process on the bootstrap runtime (the compiler
# is a host tool) and points its resource dir at the build tree, so the programs
# it produces link against the layout-2 stdlib and record it as a RUNPATH.
#
#   AGORA_PREFIX, AGORA_SWIFT_ROOT, ... as in native-env.sh
#   SWIFT_BUILD_SUBDIR   build subdirectory (default agora-<target>)

set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/native-env.sh"

BUILD_JOBS="${BUILD_JOBS:-$(nproc 2>/dev/null || echo 3)}"
SWIFT_BUILD_SUBDIR="${SWIFT_BUILD_SUBDIR:-agora-${AGORA_TARGET_TRIPLE}}"
BUILD_DIR="$OPEN_SWIFT_SOURCE_ROOT/build/$SWIFT_BUILD_SUBDIR/swift-$AGORA_TARGET_TRIPLE"
FRONTEND="$BUILD_DIR/bin/swift-frontend"
STDLIB_DIR="$BUILD_DIR/lib/swift"

if [[ ! -f "$BUILD_DIR/build.ninja" ]]; then
  echo "error: no configured build tree at $BUILD_DIR" >&2
  echo "       run build-swift-toolchain.sh once first" >&2
  exit 1
fi

# The same environment the full build uses for the target stdlib: Agora's
# headers and this build's libdispatch come first.
export CPATH="$AGORA_PREFIX/include:$OPEN_SWIFT_RUNTIME_PREFIX/include${CPATH:+:$CPATH}"
export LIBRARY_PATH="$AGORA_PREFIX/lib:$OPEN_SWIFT_RUNTIME_PREFIX/lib${LIBRARY_PATH:+:$LIBRARY_PATH}"
export LD_LIBRARY_PATH="$OPEN_SWIFT_BOOTSTRAP_TOOLCHAIN/lib/swift/linux:$OPEN_SWIFT_BOOTSTRAP_TOOLCHAIN/lib:$AGORA_PREFIX/lib:$OPEN_SWIFT_RUNTIME_PREFIX/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

echo "== configure $BUILD_DIR with SWIFT_OBJC_CLASS_LAYOUT=2 =="
"$AGORA_CMAKE" -DSWIFT_OBJC_CLASS_LAYOUT:STRING=2 "$BUILD_DIR" >/dev/null

echo "== build swift-frontend and the stdlib (layout 2) =="
echo "   (an ABI change recompiles the stdlib; allow ~15-30 minutes)"
"$AGORA_NINJA" -C "$BUILD_DIR" swift-frontend stdlib -j "$BUILD_JOBS"

# Self-check that the stdlib really is the layout-2 one: a layout-2 build emits
# the GNUstep metaclass for the runtime's own root class into libswiftCore.
# NB: no `grep -q` here - under `set -o pipefail` grep's early exit makes `nm`
# die of SIGPIPE and turns the pipeline into a failure.
if ! nm "$STDLIB_DIR/linux/libswiftCore.so" 2>/dev/null | grep '_OBJC_METACLASS__TtCs12_SwiftObject' >/dev/null; then
  echo "warning: libswiftCore.so has no _OBJC_METACLASS__TtCs12_SwiftObject;" >&2
  echo "         is it really built at layout 2?" >&2
fi

wrapper="$BUILD_DIR/bin/swiftc-layout2-stdlib"
cat > "$wrapper" <<EOF
#!/usr/bin/env bash
# Generated by swift-toolchain/scripts/build-layout2-stdlib.sh.
# The compiler is a host tool and runs on the bootstrap runtime; programs it
# produces get the layout-2 stdlib from this build tree through DT_RUNPATH.
export LD_LIBRARY_PATH="$OPEN_SWIFT_BOOTSTRAP_TOOLCHAIN/lib/swift/linux:$OPEN_SWIFT_BOOTSTRAP_TOOLCHAIN/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
exec -a swiftc "$FRONTEND" \\
  -resource-dir "$STDLIB_DIR" \\
  -tools-directory "$OPEN_SWIFT_BOOTSTRAP_TOOLCHAIN/bin" "\$@"
EOF
chmod +x "$wrapper"

echo "== done =="
echo "  compiler: $FRONTEND"
echo "  stdlib:   $STDLIB_DIR"
echo "  wrapper:  $wrapper"
echo "  gate:     $AGORA_ROOT/swift-toolchain/scripts/verify-generic-abi.sh"
