#!/usr/bin/env bash
#
# Build the compiler in the existing build tree and install a `swiftc-layout2`
# wrapper next to it.
#
# Layout 2 is the default since the 2026-10-17 flip (`Runtime/Config.h` and
# `native-env.sh`), and the installed toolchain is layout 2, so this script is
# no longer an experiment: it rebuilds `swift-frontend` in the build tree
# (useful after a compiler-source change, without reinstalling) and writes the
# convenience wrapper the gates use.  Only `swift-frontend` is built; the
# *stdlib* is not, so the wrapper reuses whatever `libswiftCore` the installed
# toolchain has - which is layout 2.  When the compiler and the stdlib come from
# different builds, prefer `build-layout2-stdlib.sh` (both from the tree) or a
# full `build-swift-toolchain.sh`.
#
#   AGORA_PREFIX, AGORA_SWIFT_ROOT, ... as in native-env.sh
#   SWIFT_BUILD_SUBDIR   build subdirectory (default agora-<target>)

set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/native-env.sh"

BUILD_JOBS="${BUILD_JOBS:-$(nproc 2>/dev/null || echo 3)}"
SWIFT_BUILD_SUBDIR="${SWIFT_BUILD_SUBDIR:-agora-${AGORA_TARGET_TRIPLE}}"
BUILD_DIR="$OPEN_SWIFT_SOURCE_ROOT/build/$SWIFT_BUILD_SUBDIR/swift-$AGORA_TARGET_TRIPLE"
FRONTEND="$BUILD_DIR/bin/swift-frontend"
TOOLCHAIN_USR="$OPEN_SWIFT_TOOLCHAIN_DESTDIR/usr"

if [[ ! -f "$BUILD_DIR/build.ninja" ]]; then
  echo "error: no configured build tree at $BUILD_DIR" >&2
  echo "       run build-swift-toolchain.sh once first" >&2
  exit 1
fi

echo "== configure $BUILD_DIR with SWIFT_OBJC_CLASS_LAYOUT=2 =="
"$AGORA_CMAKE" -DSWIFT_OBJC_CLASS_LAYOUT:STRING=2 "$BUILD_DIR" >/dev/null

echo "== build swift-frontend (layout 2) =="
"$AGORA_NINJA" -C "$BUILD_DIR" swift-frontend -j "$BUILD_JOBS"

# The compiler is a host tool and must keep running on the bootstrap runtime.
# Programs keep the installed toolchain's interop stdlib through DT_RUNPATH.
wrapper="$BUILD_DIR/bin/swiftc-layout2"
cat > "$wrapper" <<EOF
#!/usr/bin/env bash
# Generated by swift-toolchain/scripts/build-layout2-frontend.sh.
export LD_LIBRARY_PATH="$OPEN_SWIFT_BOOTSTRAP_TOOLCHAIN/lib/swift/linux:$OPEN_SWIFT_BOOTSTRAP_TOOLCHAIN/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
exec -a swiftc "$FRONTEND" \\
  -resource-dir "$TOOLCHAIN_USR/lib/swift" \\
  -tools-directory "$TOOLCHAIN_USR/bin" "\$@"
EOF
chmod +x "$wrapper"

echo "== done =="
echo "  compiler: $FRONTEND"
echo "  wrapper:  $wrapper"
echo "  gate:     $AGORA_ROOT/swift-toolchain/scripts/verify-class-abi.sh"
